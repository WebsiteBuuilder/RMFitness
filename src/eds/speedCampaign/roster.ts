// The Millennium Road: the story campaign's chapters, duelists, decks, Duel Conditions
// and star goals. Every card here is a Speed Duel card the engine can play; decks follow
// the Speed Duel rules (20-30 Main, 0-6 Fusion Extra, 3 per name) and the Limited List.
// Difficulty climbs from Starter Deck strength (chapter 1) to tuned 25-30 card decks with
// Duel Conditions (chapters 6-8). Players build their campaign deck only from cards they
// earn on the road, so early decks stay simple: mostly monsters, a few plain spells/traps.
import type { CpuDuelist, DuelCondition, StarGoal, DeckList } from './types';

export interface CampaignNode {
  id: string;
  duelist: CpuDuelist;
  boss?: boolean;
  condition?: DuelCondition;
  goal: StarGoal;
  /** a story duel: the player must use this deck instead of theirs */
  story?: { as: string; main: DeckList; extra: DeckList; skill: string | null };
}

export interface Chapter {
  id: string;
  n: number;
  title: string;
  blurb: string;
  item: string;
  itemText: string;
  nodes: CampaignNode[];
  postgame?: boolean;
}

