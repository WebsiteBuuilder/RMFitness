export const RETIRED: ReadonlySet<string> = new Set(RETIRED_PRICE.keys());

const keep = (names: string[]) => names.filter((n) => !RETIRED.has(n));

/** The deck without retired cards (the same object when it had none). */
export function dropRetired<T extends Pick<SpeedDeck, 'main' | 'extra'>>(d: T): T {
  if (!d.main.some((n) => RETIRED.has(n)) && !d.extra.some((n) => RETIRED.has(n))) return d;
  return { ...d, main: keep(d.main), extra: keep(d.extra) };
}

/** A pending Labyrinth choice without retired cards (offers made before the update). */
export function dropRetiredPending<T extends { kind: string }>(p: T | undefined): T | undefined {
  if (!p) return p;
  const q = p as unknown as { kind: string; options?: string[]; items?: { kind?: string; name: string }[]; card?: string; then?: { kind: string } };
  if (q.kind === 'draft' && q.options?.some((n) => RETIRED.has(n))) return { ...p, options: q.options.filter((n) => !RETIRED.has(n)) };
  if (q.kind === 'shop' && q.items?.some((i) => RETIRED.has(i.name))) return { ...p, items: q.items.filter((i) => !RETIRED.has(i.name)) };
  if (q.kind === 'swap' && q.card && RETIRED.has(q.card)) return (q.then as T | undefined) ?? undefined;
  return p;
}
