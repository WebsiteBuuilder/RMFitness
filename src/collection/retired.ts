const keep = (names: string[]) => names.filter((n) => !RETIRED.has(n));

/** The deck without retired cards (the same object when it had none). */
export function dropRetired<T extends Pick<SpeedDeck, 'main' | 'extra'>>(d: T): T {
  if (!d.main.some((n) => RETIRED.has(n)) && !d.extra.some((n) => RETIRED.has(n))) return d;
  return { ...d, main: keep(d.main), extra: keep(d.extra) };
}
